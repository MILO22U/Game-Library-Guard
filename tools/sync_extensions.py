"""Copy maintained shared sources into both self-contained browser packages.

Also generates:
- content-style.js: content.css as a string, so badges can be styled inside shadow DOM.
- manifest site lists: taken from the `matches:[...]` entries in shared/adapters.js,
  so the store list and the browser permissions cannot drift apart.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
shared = root / 'shared'
CONTENT_SCRIPTS = ['adapters.js', 'ownership.js', 'content-style.js', 'content.js']

css = (shared / 'content.css').read_bytes().decode('utf-8')  # keep line endings exactly
(shared / 'content-style.js').write_text(
    '// Generated by tools/sync_extensions.py from content.css. Do not edit.\n'
    'const GLG_STYLE=' + json.dumps(css) + ';\n', encoding='utf-8')

adapters = (shared / 'adapters.js').read_text(encoding='utf-8')
matches = []
for group in re.findall(r"matches:\[([^\]]*)\]", adapters):
    for pattern in re.findall(r"'([^']+)'", group):
        if pattern not in matches:
            matches.append(pattern)
if not matches:
    raise SystemExit('No store match patterns found in shared/adapters.js')

for browser in ('chrome', 'firefox'):
    for name in ('popup.html', 'popup.css', 'popup.js', 'library.js', 'adapters.js', 'ownership.js',
                 'content.js', 'content.css', 'content-style.js'):
        (root / browser / name).write_bytes((shared / name).read_bytes())
    (root / browser / 'background.js').write_bytes(
        (shared / 'library.js').read_bytes() + b'\n' + (shared / 'background.js').read_bytes())
    manifest_path = root / browser / 'manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    manifest['host_permissions'] = matches
    manifest['content_scripts'][0]['matches'] = matches
    manifest['content_scripts'][0]['js'] = CONTENT_SCRIPTS
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')

print(f'Chrome and Firefox packages synchronized ({len(matches)} site patterns).')
